import assert from 'node:assert/strict';
import { calendarWeek, parseFitDay, summarizeWeek } from '../src/utils/activityData.js';
process.env.TZ = 'Asia/Kolkata';
const now = new Date(2026, 9, 9, 15, 30);
const week = calendarWeek(now);
assert.equal(week.length, 7);
assert.equal(week[0].dateKey, '2026-10-03');
assert.equal(new Date(week[6].start).getHours(), 0);
assert.equal(week[6].end, +now);
const missing = parseFitDay({ bucket: [{ dataset: [] }] }, week[0]);
assert.equal(missing.steps, null);
assert.equal(missing.heartRate, null);
const point = (dataSourceId, values) => ({ dataSourceId, point: values.map(value => ({ value: [{ fpVal: value }] })) });
const day = parseFitDay({ bucket: [{ dataset: [point('step_count', [0]), point('calories', [100.4, 100.4]), point('heart_rate', [80])] }] }, week[1]);
assert.equal(day.steps, 0);
assert.equal(day.calories, 201);
const summary = summarizeWeek([missing, day, { ...week[6], steps: 100, heartRate: null }], 'Google Fit');
assert.equal(summary.averages.avgSteps, 50, 'Reported zero is part of the average');
assert.equal(summary.today.heartRate.current, null, 'Do not carry a prior heart rate into today');
assert.equal(summary.today.recovery.current, null, 'Do not fabricate recovery');
process.env.TZ = 'America/New_York';
const dst = calendarWeek(new Date(2026, 2, 10, 15));
const transition = dst.find(day => day.dateKey === '2026-03-08');
assert.equal(transition.end - transition.start, 23 * 60 * 60 * 1000, 'Calendar days respect daylight saving');
console.log('PASS calendar boundaries, DST, zero versus missing, calorie rounding, averages and no fabricated readings');
